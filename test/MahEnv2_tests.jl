#--------------------------------------------------------------------------------------------------
# MahEnv2 tests (p=2 specialisation of MahEnv)
#--------------------------------------------------------------------------------------------------
using Test
using Hensel

#--------------------------------------------------------------------------------------------------

fe  = Hensel.FunEnv((x) -> 3*x+2, (0, 1), 2, 8, (2, 5))
fe2 = Hensel.FunEnv2((x) -> 3*x+2, (0, 1), 8, (2, 5))

me  = Hensel.MahEnv(fe)
me2 = Hensel.MahEnv2(fe2)

@test me2.mv == me.mv

for n = 0:9
    @test me2(n) == me(n)
    @test me2(n, 5) == me(n, 5)
    @test me2(n, "Mahler") == me(n, "Mahler")
    @test me2(n, "Hensel") == me(n, "Hensel")
    @test Hensel.δ(me2, n) == Hensel.δ(me, n)
    @test Hensel.δ(me2, n, 5) == Hensel.δ(me, n, 5)
end

for x in [0.0, 0.1, 0.25, 0.5, 0.75, 0.999]
    @test me2(x) == me(x)
    @test me2(x, 5) == me(x, 5)
end

#--------------------------------------------------------------------------------------------------
# explicit length constructor
#--------------------------------------------------------------------------------------------------

me3  = Hensel.MahEnv(fe, 6)
me32 = Hensel.MahEnv2(fe2, 6)
@test me32.mv == me3.mv

