#--------------------------------------------------------------------------------------------------
# FunEnv2 tests (p=2 specialisation of FunEnv)
#--------------------------------------------------------------------------------------------------
using Test
using Hensel

#--------------------------------------------------------------------------------------------------

@test Hensel.FunEnv2((x) -> x+1, (0, 1), 5, (1, 2))(0.25) == Hensel.FunEnv((x) -> x+1, (0, 1), 2, 5, (1, 2))(0.25)

@test Hensel.FunEnv2((x) -> x+1, (0, 1), 5, (1, 2))(2) == Hensel.FunEnv((x) -> x+1, (0, 1), 2, 5, (1, 2))(2)
@test Hensel.FunEnv2((x) -> x+1, (0, 1), 5, (1, 2))(2, return_type="hensel") ==
      Hensel.FunEnv((x) -> x+1, (0, 1), 2, 5, (1, 2))(2, return_type="hensel")
@test Hensel.FunEnv2((x) -> x+1, (0, 1), 5, (1, 2))(2, return_type="real") ==
      Hensel.FunEnv((x) -> x+1, (0, 1), 2, 5, (1, 2))(2, return_type="real")
@test Hensel.FunEnv2((x) -> x+1, (0, 1), 5, (1, 2)).(0:9) == Hensel.FunEnv((x) -> x+1, (0, 1), 2, 5, (1, 2)).(0:9)
@test ((y) -> Hensel.FunEnv2((x) -> x+1, (0, 1), 5, (1, 2))(y, return_type="real")).(0:9) ==
      ((y) -> Hensel.FunEnv((x) -> x+1, (0, 1), 2, 5, (1, 2))(y, return_type="real")).(0:9)

@test Hensel.FunEnv2((x) -> 0.6*x*(1.0-x), (0.0, 1.0), 8, (0.0, 1.0)).(0:10) ==
      Hensel.FunEnv((x) -> 0.6*x*(1.0-x), (0.0, 1.0), 2, 8, (0.0, 1.0)).(0:10)
@test Hensel.FunEnv2((x) -> 0.6*x*(1-x), (0.0, 1.0), 8, (0.0, 1.0))(0.5) ==
      Hensel.FunEnv((x) -> 0.6*x*(1-x), (0.0, 1.0), 2, 8, (0.0, 1.0))(0.5)

#--------------------------------------------------------------------------------------------------

@test ((y) -> Hensel.δ(Hensel.FunEnv2((x) -> 3*x+2, (0, 1), 8, (2, 5)), y))(0.3) ==
      ((y) -> Hensel.δ(Hensel.FunEnv((x) -> 3*x+2, (0, 1), 2, 8, (2, 5)), y))(0.3)
@test ((y) -> Hensel.δ(y, Hensel.FunEnv2((x) -> 3*x+2, (0, 1), 8, (2, 5))))(0.3) ==
      ((y) -> Hensel.δ(y, Hensel.FunEnv((x) -> 3*x+2, (0, 1), 2, 8, (2, 5))))(0.3)

#--------------------------------------------------------------------------------------------------

@test Hensel.mexpansion(Hensel.FunEnv2((x) -> 3*x+2, (0, 1), 8, (2, 5)), 8) ==
      Hensel.mexpansion(Hensel.FunEnv((x) -> 3*x+2, (0, 1), 2, 8, (2, 5)), 8)
